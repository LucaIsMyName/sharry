export function AppIcon({
  name,
  size = 16,
  className,
}: {
  name: string | null | undefined;
  size?: number;
  className?: string;
}) {
  const Icon = isIconName(name) ? icons[name] : null;
  if (!Icon) return null;
  return <Icon size={size} className={className} aria-hidden />;
}
